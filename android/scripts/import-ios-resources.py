#!/usr/bin/env python3
"""Copies what the Android placeholder module uses from the iOS bundle (CYLTableViewPlaceHolder.bundle).

Images: the static icons of the ported scenarios, CYLPlaceholderSearchOff@2x.png -> res/drawable-xhdpi/
cyl_placeholder_search_off.png. Strings: every key of <lang>.lproj/Localizable.strings ("CYLPlaceholderX" ->
<string name="cyl_placeholder_x">) in res/values[-<lang>]/cyl_placeholder_strings.xml, iOS format specifiers turned
into Java ones. Animations: every CYLPlaceholder*.json and *.gif of Animations/ with the licenses and notices, to
assets/CYLPlaceholderAnimations/ (played when an animator for them is registered, such as module placeholder-lottie).
Run: python3 android/scripts/import-ios-resources.py
"""
import os, re, shutil
from xml.sax.saxutils import escape

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BUNDLE = os.path.join(ROOT, 'CYLTableViewPlaceHolder', 'CYLTableViewPlaceHolder', 'CYLTableViewPlaceHolder.bundle')
RES = os.path.join(ROOT, 'android', 'placeholder', 'src', 'main', 'res')
ANIMATIONS = os.path.join(ROOT, 'android', 'placeholder', 'src', 'main', 'assets', 'CYLPlaceholderAnimations')
IMAGES = [
    # Every CYLPlaceholderStyle, in the iOS order (CYLPlaceholderView.imageNameForStyle).
    'Empty', 'NoResults', 'Error', 'WifiOff', 'SignalWifiOff', 'NoInternet', 'CloudOff', 'SyncProblem', 'SyncDisabled',
    'NetworkLocked', 'BluetoothDisabled', 'LocationOff', 'PublicOff', 'ErrorOutline', 'Warning', 'ReportProblem', 'Blocked',
    'Help', 'Hourglass', 'Locked', 'VisibilityOff', 'SearchOff', 'FolderOff', 'FolderOpen', 'DownloadOff', 'UploadOff',
    'Inbox', 'BrokenImage', 'ImageUnavailable', 'PhotoLibrary', 'MusicOff', 'VideoOff', 'PersonOff', 'GroupOff', 'EventBusy',
    'EmptyCart', 'Favorite', 'BatteryAlert', 'UnknownDevice', 'PhoneDisabled', 'WrongLocation', 'Archive', 'Info', 'Refresh',
    'Delete', 'Search', 'Mail', 'Image', 'Cloud', 'NotificationsOff', 'History',
    # The status banner's icon (CYLPlaceholderStatusView).
    'StatusFail',
]
LANGS = {'en': 'values', 'ja': 'values-ja', 'ko': 'values-ko', 'ru': 'values-ru', 'uk': 'values-uk',
         'zh-Hans': 'values-b+zh+Hans', 'zh-Hant': 'values-b+zh+Hant'}


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()


def main():
    drawable = os.path.join(RES, 'drawable-xhdpi')
    os.makedirs(drawable, exist_ok=True)
    for name in IMAGES:
        for candidate in (f'CYLPlaceholder{name}@2x.png', f'CYLPlaceholder{name}.png'):
            path = os.path.join(BUNDLE, candidate)
            if os.path.exists(path):
                shutil.copyfile(path, os.path.join(drawable, f'cyl_placeholder_{snake(name)}.png'))
                break
        else:
            raise SystemExit(f'missing image {name}')
    for lang, folder in LANGS.items():
        text = open(os.path.join(BUNDLE, f'{lang}.lproj', 'Localizable.strings'), encoding='utf-8').read()
        pairs = re.findall(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', text, re.M)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 f'<!-- Generated by android/scripts/import-ios-resources.py from the iOS {lang}.lproj. Do not edit. -->',
                 '<resources>']
        for key, value in pairs:
            value = value.replace('\\"', '"').replace('\\n', '\n')
            has_format = re.search(r'%(\d+\$)?l?[ud@]', value)
            value = re.sub(r'%(\d+\$)?l?[ud]', lambda m: '%' + (m.group(1) or '') + 'd', value)
            value = re.sub(r'%(\d+\$)?@', lambda m: '%' + (m.group(1) or '') + 's', value)
            value = escape(value).replace("'", "\\'").replace('"', '\\"')
            if value.startswith('@') or value.startswith('?'):
                value = '\\' + value
            formatted = '' if has_format else (' formatted="false"' if '%' in value else '')
            name = 'cyl_placeholder_' + snake(key.removeprefix('CYLPlaceholder')).replace('.', '_')
            lines.append(f'    <string name="{name}"{formatted}>{value}</string>')
        lines.append('</resources>')
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        open(os.path.join(RES, folder, 'cyl_placeholder_strings.xml'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    os.makedirs(ANIMATIONS, exist_ok=True)
    source = os.path.join(BUNDLE, 'Animations')
    animations = sorted(n for n in os.listdir(source) if not n.startswith('._') and (
        (n.startswith('CYLPlaceholder') and n.endswith(('.json', '.gif'))) or n.startswith(('LICENSE', 'NOTICE'))))
    for name in animations:
        shutil.copyfile(os.path.join(source, name), os.path.join(ANIMATIONS, name))
    print('images:', len(IMAGES), 'languages:', len(LANGS), 'animation files:', len(animations))


if __name__ == '__main__':
    main()
