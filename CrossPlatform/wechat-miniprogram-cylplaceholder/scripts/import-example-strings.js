// Copies the iOS example's own texts (Examples/Example-Scenarios/Sources/CYLScenarioExample.bundle/<lang>.lproj/*.strings)
// into the mini program example (example/miniprogram/utils/strings/<lang>.js), and its configuration files.
// Usage (from the package folder): node scripts/import-example-strings.js
'use strict'
const fs = require('fs')
const path = require('path')

const pkg = path.resolve(__dirname, '..')
const bundle = path.resolve(pkg, '../../Examples/Example-Scenarios/Sources/CYLScenarioExample.bundle')
const out = path.join(pkg, 'example/miniprogram/utils/strings')
const LANGUAGES = ['en', 'zh-Hans', 'zh-Hant', 'ja', 'ko', 'ru', 'uk']

/** Parses a .strings file: "key" = "value"; with \" \n \\ escapes; comments skipped. */
function parseStrings(text) {
  const table = {}
  const re = /"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;/g
  const unescape = (s) => s.replace(/\\(["\\n])/g, (_, c) => (c === 'n' ? '\n' : c))
  for (const m of text.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(re)) table[unescape(m[1])] = unescape(m[2])
  return table
}

fs.mkdirSync(out, { recursive: true })
for (const language of LANGUAGES) {
  const table = {}
  for (const file of ['CYLScenarioExample.strings', 'CYLRefreshCustom.strings']) {
    const p = path.join(bundle, language + '.lproj', file)
    if (fs.existsSync(p)) Object.assign(table, parseStrings(fs.readFileSync(p, 'utf8')))
  }
  fs.writeFileSync(path.join(out, language + '.js'), '// Generated by scripts/import-example-strings.js from CYLScenarioExample.bundle. Do not edit.\nmodule.exports = ' + JSON.stringify(table, null, 2) + '\n')
  console.log(language, Object.keys(table).length)
}

const configurations = path.join(pkg, 'example/miniprogram/configurations')
fs.mkdirSync(configurations, { recursive: true })
// A mini program package keeps only known file types (not .plist): a property list ships as <name>.plist.json
// holding the XML as one JSON string (CYLPlaceholderConfiguration.readConfigurationFile reads it).
for (const f of fs.readdirSync(path.join(bundle, 'Configurations'))) {
  const source = fs.readFileSync(path.join(bundle, 'Configurations', f), 'utf8')
  if (/\.plist$/.test(f)) fs.writeFileSync(path.join(configurations, f + '.json'), JSON.stringify(source) + '\n')
  else fs.writeFileSync(path.join(configurations, f), source)
}
console.log('configurations', fs.readdirSync(configurations).join(', '))
