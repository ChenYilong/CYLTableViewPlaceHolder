// Copies the placeholder icons and strings of android/placeholder into the mini program package.
// Usage (from the package folder): node scripts/import-android-resources.js
'use strict'
const fs = require('fs')
const path = require('path')

const pkg = path.resolve(__dirname, '..')
const res = path.resolve(pkg, '../../android/placeholder/src/main/res')
const out = path.join(pkg, 'src/cyl-placeholder')
const locales = { values: 'en', 'values-b+zh+Hans': 'zh-Hans', 'values-b+zh+Hant': 'zh-Hant', 'values-ja': 'ja', 'values-ko': 'ko', 'values-ru': 'ru', 'values-uk': 'uk' }

// Android string escapes: \' \" \n \\ and the XML entities.
const unescape = (s) => s.replace(/\\(['"n\\@?])/g, (_, c) => (c === 'n' ? '\n' : c)).replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')

for (const [folder, locale] of Object.entries(locales)) {
  const xml = fs.readFileSync(path.join(res, folder, 'cyl_placeholder_strings.xml'), 'utf8')
  const strings = {}
  for (const m of xml.matchAll(/<string name="cyl_placeholder_([a-z0-9_]+)"[^>]*>([\s\S]*?)<\/string>/g)) strings[m[1]] = unescape(m[2])
  const json = JSON.stringify(strings, null, 2)
  fs.writeFileSync(path.join(out, 'locales', locale + '.json'), json + '\n')
  // Mini program require() does not load .json files on every base library; the .js twin is what the code loads.
  fs.writeFileSync(path.join(out, 'locales', locale + '.js'), '// Generated by scripts/import-android-resources.js. Do not edit.\nmodule.exports = ' + json + '\n')
  console.log(locale, Object.keys(strings).length)
}

const drawables = path.join(res, 'drawable-xhdpi')
for (const f of fs.readdirSync(drawables).filter((f) => f.startsWith('cyl_placeholder_') && f.endsWith('.png'))) {
  fs.copyFileSync(path.join(drawables, f), path.join(out, 'images', f.replace(/^cyl_placeholder_/, '')))
}
console.log('icons', fs.readdirSync(path.join(out, 'images')).length)
