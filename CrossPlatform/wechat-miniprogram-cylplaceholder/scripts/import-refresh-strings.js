// Copies CYLRefresh's texts (CYLTableViewPlaceHolder.bundle/<lang>.lproj/CYLRefresh.strings, 7 languages) into
// src/cyl-refresh/locales/<lang>.js. Usage (from the package folder): node scripts/import-refresh-strings.js
'use strict'
const fs = require('fs')
const path = require('path')

const pkg = path.resolve(__dirname, '..')
const bundle = path.resolve(pkg, '../../CYLTableViewPlaceHolder/CYLTableViewPlaceHolder/CYLTableViewPlaceHolder.bundle')
const out = path.join(pkg, 'src/cyl-refresh/locales')
const unescape = (s) => s.replace(/\\(["\\n])/g, (_, c) => (c === 'n' ? '\n' : c))

fs.mkdirSync(out, { recursive: true })
for (const language of ['en', 'zh-Hans', 'zh-Hant', 'ja', 'ko', 'ru', 'uk']) {
  const text = fs.readFileSync(path.join(bundle, language + '.lproj', 'CYLRefresh.strings'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
  const table = {}
  for (const m of text.matchAll(/"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;/g)) table[unescape(m[1])] = unescape(m[2])
  fs.writeFileSync(path.join(out, language + '.js'), '// Generated by scripts/import-refresh-strings.js from CYLRefresh.strings. Do not edit.\nmodule.exports = ' + JSON.stringify(table, null, 2) + '\n')
  console.log(language, Object.keys(table).length)
}
