#!/usr/bin/env node
// Copies the tab bar texts this project uses from CYLTabBarController's string table
// (CYLTabBarController/Resources/CYLTabBarController.bundle/<lang>.lproj/CYLTabBarController.strings; the key is the
// original text) into one ArkTS module of the example, for the example's seven languages:
//   node scripts/import-tabbar-strings.js [path/to/CYLTabBarController]
//   -> entry/src/main/ets/common/TabBarStrings.ets
// Only the keys in KEYS are copied: the ones the example's tab bar and playback controls speak (VoiceOver / screen
// reader labels and values). Default source: the sibling checkout ../../../CYLTabBarController.
'use strict'
const fs = require('fs')
const path = require('path')

const HERE = path.join(__dirname, '..')
const SOURCE = process.argv[2] || path.join(HERE, '..', '..', '..', 'CYLTabBarController')
const BUNDLE = path.join(SOURCE, 'CYLTabBarController', 'Resources', 'CYLTabBarController.bundle')
const OUT = path.join(HERE, 'entry', 'src', 'main', 'ets', 'common', 'TabBarStrings.ets')
const LANGUAGES = ['en', 'zh-Hans', 'zh-Hant', 'ja', 'ko', 'ru', 'uk']
// Key (CYLTabBarController's original text) -> the name the example uses.
const KEYS = {
  '选中': 'Selected',
  '加号按钮': 'PlusButton',
  '关闭': 'Close',
  '播放 / 停止': 'PlayStop',
  '角标': 'Badges',
}

function parse(file) {
  const table = {}
  const text = fs.readFileSync(file, 'utf8')
  const re = /^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";/gm
  let m
  while ((m = re.exec(text)) !== null) table[JSON.parse('"' + m[1] + '"')] = JSON.parse('"' + m[2] + '"')
  return table
}

let commit = ''
try {
  commit = require('child_process').execSync('git -C "' + SOURCE + '" rev-parse --short HEAD').toString().trim()
} catch (e) {
  commit = 'unknown'
}
let out = '// Generated by scripts/import-tabbar-strings.js from CYLTabBarController.bundle (CYLTabBarController ' + commit +
  '). Do not edit.\n// The tab bar texts the example speaks, in its seven languages (keys: the CYLTabBarController original texts).\n'
out += '\nconst TAB_BAR_STRINGS: Record<string, Record<string, string>> = {\n'
for (const lang of LANGUAGES) {
  const table = parse(path.join(BUNDLE, lang + '.lproj', 'CYLTabBarController.strings'))
  const rows = Object.keys(KEYS).map((key) => {
    if (table[key] === undefined) throw new Error(`${lang}: missing "${key}"`)
    return `    ${JSON.stringify(KEYS[key])}: ${JSON.stringify(table[key])},`
  })
  out += `  ${JSON.stringify(lang)}: {\n${rows.join('\n')}\n  },\n`
}
out += '};\n\n'
out += '/** A tab bar text ("Selected", "PlusButton", "Close", "PlayStop", "Badges") in a language; English otherwise. */\n'
out += 'export function tabBarText(name: string, language: string): string {\n'
out += "  const table = TAB_BAR_STRINGS[language] !== undefined ? TAB_BAR_STRINGS[language] : TAB_BAR_STRINGS['en'];\n"
out += "  return table[name] !== undefined ? table[name] : TAB_BAR_STRINGS['en'][name];\n}\n"
fs.writeFileSync(OUT, out)
console.log('wrote', path.relative(HERE, OUT), 'from CYLTabBarController', commit)
