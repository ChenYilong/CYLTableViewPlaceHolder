#!/usr/bin/env node
// Imports the example's own texts (CYLScenarioLocalizedString of the iOS example, CYLScenarioExample.bundle) from
// the WeChat Mini Program example (utils/strings/<lang>.js) as one ArkTS module of the example (not the library):
//   node scripts/import-example-strings.js   ->   entry/src/main/ets/common/ExampleStrings.ets
'use strict'
const fs = require('fs')
const path = require('path')

const HERE = path.join(__dirname, '..')
const MP = path.join(HERE, '..', 'wechat-miniprogram-cylplaceholder', 'example', 'miniprogram', 'utils', 'strings')
const OUT = path.join(HERE, 'entry', 'src', 'main', 'ets', 'common', 'ExampleStrings.ets')
const LANGUAGES = ['en', 'zh-Hans', 'zh-Hant', 'ja', 'ko', 'ru', 'uk']
const NAMES = { en: 'En', 'zh-Hans': 'ZhHans', 'zh-Hant': 'ZhHant', ja: 'Ja', ko: 'Ko', ru: 'Ru', uk: 'Uk' }

let out = '// Generated by scripts/import-example-strings.js from CYLScenarioExample.bundle (via the mini program). Do not edit.\n'
for (const code of LANGUAGES) {
  const table = require(path.join(MP, code + '.js'))
  const body = Object.keys(table).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(table[k]) + ',').join('\n')
  out += '\nconst ExampleStrings' + NAMES[code] + ': Record<string, string> = {\n' + body + '\n};\n'
}
out += '\n/** Language code -> the example texts in that language. */\nexport function ExampleStringTable(code: string): Record<string, string> {\n'
out += '  switch (code) {\n'
for (const code of LANGUAGES.slice(1)) out += "    case '" + code + "':\n      return ExampleStrings" + NAMES[code] + ';\n'
out += '    default:\n      return ExampleStringsEn;\n  }\n}\n'
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, out)
console.log('wrote', path.relative(HERE, OUT))
