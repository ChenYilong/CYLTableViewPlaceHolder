#!/usr/bin/env node
// Imports the CYLRefresh resources: the 7 refresh string tables (CYLRefresh.strings, via the WeChat Mini Program
// package) as ArkTS modules, and the refresh images and bundled refresh animations of the iOS bundle as rawfiles.
//   node scripts/import-refresh-resources.js
'use strict'
const fs = require('fs')
const path = require('path')

const HERE = path.join(__dirname, '..')
const ROOT = path.join(HERE, '..', '..')
const MP = path.join(HERE, '..', 'wechat-miniprogram-cylplaceholder', 'src', 'cyl-refresh')
const BUNDLE = path.join(ROOT, 'CYLTableViewPlaceHolder', 'CYLTableViewPlaceHolder', 'CYLTableViewPlaceHolder.bundle')
const LIB = path.join(HERE, 'cylplaceholder', 'src', 'main')
const LOCALES = { en: 'En', 'zh-Hans': 'ZhHans', 'zh-Hant': 'ZhHant', ja: 'Ja', ko: 'Ko', ru: 'Ru', uk: 'Uk' }

const out = path.join(LIB, 'ets', 'refresh', 'locales')
fs.mkdirSync(out, { recursive: true })
for (const [code, suffix] of Object.entries(LOCALES)) {
  const table = require(path.join(MP, 'locales', code + '.js'))
  const body = Object.keys(table).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(table[k]) + ',').join('\n')
  fs.writeFileSync(path.join(out, 'CYLRefreshStrings' + suffix + '.ets'),
    '// Generated by scripts/import-refresh-resources.js from CYLRefresh.strings (via the mini program package). Do not edit.\n' +
    'export const CYLRefreshStrings' + suffix + ': Record<string, string> = {\n' + body + '\n};\n')
}

const raw = path.join(LIB, 'resources', 'rawfile', 'cylplaceholder', 'refresh')
fs.mkdirSync(raw, { recursive: true })
for (const f of ['CYLRefreshArrow@2x.png', 'CYLRefreshTrailArrow@2x.png']) {
  fs.copyFileSync(path.join(BUNDLE, f), path.join(raw, f))
}
for (const f of ['CYLRefreshArrows.gif', 'CYLRefreshPullArrow.json']) {
  fs.copyFileSync(path.join(BUNDLE, 'Animations', f), path.join(raw, f))
}
console.log('imported 7 refresh string tables, 2 refresh images and 2 refresh animations')
