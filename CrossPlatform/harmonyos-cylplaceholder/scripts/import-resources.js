#!/usr/bin/env node
// Imports the shared resources of the library from the WeChat Mini Program package (itself imported from
// android/placeholder): the 7 string tables as ArkTS modules, the icons and the bundled animations as rawfiles.
//   node scripts/import-resources.js
'use strict'
const fs = require('fs')
const path = require('path')

const HERE = path.join(__dirname, '..')
const MP = path.join(HERE, '..', 'wechat-miniprogram-cylplaceholder', 'src', 'cyl-placeholder')
const LIB = path.join(HERE, 'cylplaceholder', 'src', 'main')
const LOCALES = { en: 'En', 'zh-Hans': 'ZhHans', 'zh-Hant': 'ZhHant', ja: 'Ja', ko: 'Ko', ru: 'Ru', uk: 'Uk' }

const out = path.join(LIB, 'ets', 'locales')
fs.mkdirSync(out, { recursive: true })
for (const [code, suffix] of Object.entries(LOCALES)) {
  const table = require(path.join(MP, 'locales', code + '.js'))
  const body = Object.keys(table).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(table[k]) + ',').join('\n')
  fs.writeFileSync(path.join(out, 'CYLPlaceholderStrings' + suffix + '.ets'),
    '// Generated by scripts/import-resources.js from android/placeholder (via the mini program package). Do not edit.\n' +
    'export const CYLPlaceholderStrings' + suffix + ': Record<string, string> = {\n' + body + '\n};\n')
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true })
  for (const f of fs.readdirSync(from)) {
    const src = path.join(from, f)
    if (fs.statSync(src).isFile()) fs.copyFileSync(src, path.join(to, f))
  }
}
copyDir(path.join(MP, 'images'), path.join(LIB, 'resources', 'rawfile', 'cylplaceholder', 'images'))
copyDir(path.join(MP, 'animations'), path.join(LIB, 'resources', 'rawfile', 'cylplaceholder', 'animations'))
for (const f of ['LICENSE.material-design-icons', 'NOTICE.material-design-icons', 'LICENSE.CYLChatKit', 'LICENSE.placeholder-third-party']) {
  fs.copyFileSync(path.join(MP, '..', '..', f), path.join(HERE, f))
}
console.log('imported 7 string tables, icons and animations')
